#!/usr/bin/env python3
"""Build the curated PocketJS icon atlas and its Rust lookup table.

Requires Pillow and ImageMagick's `convert` with SVG support. Inputs are the
IconaMoon Color SVGs; outputs are deterministic 24px cells in app/static.
"""
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('/home/evelyn/git/icons/IconaMoon/SVG/Color')
ICONS = [
    ('refresh', 'Interface/Synchronize - SVG.svg'),
    ('back', 'Arrow/Arrow Left 1 - SVG.svg'),
    ('next', 'Arrow/Arrow Right 2 - SVG.svg'),
    ('close', 'Interface/Close - SVG.svg'),
]
CELL = 32
COLS = 4


def main() -> None:
    from PIL import Image

    atlas = Image.new('RGBA', (COLS * CELL, ((len(ICONS) + COLS - 1) // COLS) * CELL), (0, 0, 0, 0))
    with tempfile.TemporaryDirectory() as tmp:
        for index, (name, relative) in enumerate(ICONS):
            source = SOURCE / relative
            if not source.is_file():
                raise SystemExit(f'missing IconaMoon source: {source}')
            rendered = Path(tmp) / f'{name}.png'
            subprocess.run(['convert', '-background', 'none', '-density', '192', str(source), '-resize', '24x24', str(rendered)], check=True)
            with Image.open(rendered) as image:
                image = image.convert('RGBA')
                atlas.alpha_composite(image, ((index % COLS) * CELL + 4, (index // COLS) * CELL + 4))
    atlas.save(ROOT / 'app/static/pocket_icons.png', optimize=False)
    entries = ',\n'.join(f'    ("{name}", {index})' for index, (name, _) in enumerate(ICONS))
    module = f'''//! Generated by tools/build-pocket-icons.py; do not edit.\n\n/// Atlas cell size in pixels.\npub const ICON_CELL_SIZE: u32 = {CELL};\n/// Number of atlas columns.\npub const ICON_ATLAS_COLUMNS: u32 = {COLS};\n/// Stable icon names and zero-based atlas cell indices.\npub const POCKET_ICONS: &[(&str, u16)] = &[\n{entries}\n];\n\n/// Resolve a stable icon name to its atlas cell index.\npub fn pocket_icon_index(name: &str) -> Option<u16> {{\n    POCKET_ICONS.iter().find_map(|(key, index)| (*key == name).then_some(*index))\n}}\n'''
    (ROOT / 'crates/bsky-render/src/pocket_icon_table.rs').write_text(module, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
