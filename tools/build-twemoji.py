#!/usr/bin/env python3
import hashlib
import io
import os
import tempfile
from pathlib import Path

import requests
from PIL import Image

RANGES = [
    (0x1F600, 0x1F650), (0x1F910, 0x1F930), (0x1F970, 0x1F980),
    (0x1F47B, 0x1F480), (0x1F636, 0x1F640), (0x1F44A, 0x1F450),
    (0x1F590, 0x1F596), (0x1F918, 0x1F920), (0x1F932, 0x1F94A),
    (0x1F491, 0x1F49F), (0x1F90D, 0x1F910), (0x2763, 0x2766),
    (0x1F40F, 0x1F44A), (0x1F980, 0x1F9B0), (0x1F32D, 0x1F37F),
    (0x1F950, 0x1F970), (0x1F330, 0x1F33F), (0x1F300, 0x1F320),
    (0x2600, 0x2620), (0x1F680, 0x1F6A0), (0x1F6A2, 0x1F6B0),
    (0x1F3A0, 0x1F3D0), (0x26BD, 0x26C0), (0x1F4A1, 0x1F4B0),
    (0x1F4DA, 0x1F4F8), (0x1F525, 0x1F526), (0x1F4AF, 0x1F4B0),
    (0x1F550, 0x1F568), (0x2705, 0x2706), (0x274C, 0x274F),
    (0x2728, 0x2729), (0x2B50, 0x2B51),
]
EXTRAS = [0x2764,0x1F308,0x1F31F,0x1F389,0x1F38A,0x1F4A5,0x1F4A8,0x1F4AB,0x1F4AC,0x1F4AD,0x26A1,0x2614,0x26C5,0x2B55,0x261D,0x1F44F,0x1F44D,0x1F44E,0x1F4F1,0x1F4BB,0x1F4F7,0x1F30D,0x1F30E,0x1F30F]
SEQUENCES = [(0x1F44D,0x1F3FD),(0x1F1EC,0x1F1E7),(0x31,0x20E3),(0x1F469,0x200D,0x1F4BB),(0x1FAF6,)]
ATLAS_COLS, CELL_PX = 16, 64
TWEMOJI_VERSION = "14.0.3"
TWEMOJI_BASE = f"https://cdn.jsdelivr.net/gh/twitter/twemoji@{TWEMOJI_VERSION}/assets/72x72"
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
OUT_PNG = REPO_ROOT / "app/static/twemoji.png"
OUT_RS = REPO_ROOT / "crates/bsky-render/src/emoji_table.rs"


def collect_codepoints():
    return sorted({cp for start, end in RANGES for cp in range(start, end)} | set(EXTRAS))


def fetch_glyph(session, key):
    asset = "-".join(f"{cp:x}" for cp in key if cp != 0xFE0F)
    try:
        response = session.get(f"{TWEMOJI_BASE}/{asset}.png", timeout=10)
    except requests.RequestException:
        raise
    if response.status_code == 404:
        return None
    response.raise_for_status()
    try:
        return Image.open(io.BytesIO(response.content)).convert("RGBA")
    except Exception as error:
        raise ValueError(f"Invalid Twemoji PNG for {asset}") from error


def source_for(table, rows, fingerprint):
    lines = ["// @generated by tools/build-twemoji.py — do not edit by hand.", "// Entries sorted by sequence for lookup.", "", f"pub const ATLAS_COLS: u16 = {ATLAS_COLS};", f"pub const ATLAS_ROWS: u16 = {rows};", f"pub const CELL_PX: u16 = {CELL_PX};", f"pub const ATLAS_FINGERPRINT: &str = \"{fingerprint}\";", "", "pub static EMOJI_TABLE: &[(&[u32], u16, u16)] = &["]
    for sequence, col, row in sorted(table, key=lambda entry: entry[0]):
        values = ", ".join(f"{cp:#08x}" for cp in sequence)
        lines.append(f"    (&[{values}], {col:>2}, {row:>2}),")
    lines.extend(["];"])
    lines.extend(["", "pub fn lookup_sequence(sequence: &str) -> Option<(u16, u16)> {", "    if sequence.contains('\\u{fe0e}') { return None; }", "    let normalized: String = sequence.chars().filter(|&ch| ch != '\\u{fe0f}').collect();", "    let codepoints: Vec<u32> = normalized.chars().map(|ch| ch as u32).collect();", "    EMOJI_TABLE.iter().find(|(candidate, _, _)| *candidate == codepoints).map(|(_, col, row)| (*col, *row))", "}", "", "pub fn lookup(codepoint: u32) -> Option<(u16, u16)> {", "    lookup_sequence(&char::from_u32(codepoint)?.to_string())", "}"])
    return "\n".join(lines) + "\n"


def main():
    keys = [(cp,) for cp in collect_codepoints()] + SEQUENCES
    session = requests.Session()
    glyphs = []
    for index, key in enumerate(keys, 1):
        glyph = fetch_glyph(session, key)
        if glyph is None:
            if len(key) > 1:
                raise ValueError(f"Pinned Twemoji set lacks sequence {'-'.join(f'{cp:x}' for cp in key)}")
            continue
        glyphs.append((key, glyph.resize((CELL_PX, CELL_PX), Image.Resampling.LANCZOS)))
        if index % 50 == 0:
            print(f"Fetched {index}/{len(keys)}")
    rows = (len(glyphs) + ATLAS_COLS - 1) // ATLAS_COLS
    atlas = Image.new("RGBA", (ATLAS_COLS * CELL_PX, rows * CELL_PX))
    table = []
    for index, (sequence, glyph) in enumerate(glyphs):
        col, row = index % ATLAS_COLS, index // ATLAS_COLS
        atlas.paste(glyph, (col * CELL_PX, row * CELL_PX))
        table.append((sequence, col, row))
    buffer = io.BytesIO()
    atlas.save(buffer, format="PNG", optimize=True)
    png_data = buffer.getvalue()
    fingerprint = hashlib.sha256(png_data).hexdigest()
    rs_data = source_for(table, rows, fingerprint).encode()
    staged = []
    try:
        for destination, data in ((OUT_PNG, png_data), (OUT_RS, rs_data)):
            destination.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as stream:
                stream.write(data)
                staged.append((Path(stream.name), destination))
        for temporary, destination in staged:
            os.replace(temporary, destination)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)
    print(f"Wrote {len(table)} emoji; atlas {atlas.width}x{atlas.height}, {len(png_data)} bytes, {atlas.width*atlas.height*4} bytes decoded RGBA")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
